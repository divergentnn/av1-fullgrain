#!/bin/sh
# browser/web/grain-wgsl.mjs <- gpu/src/grain.wgsl: the grain shaders have one source, shared by the browser kit
# (gpu-grain.mjs) and the native renderer (gpu/). Run after editing grain.wgsl; `cargo test` in gpu/ checks that the
# two match.
#
# Copyright © 2026, divergentnn (av1-fullgrain). SPDX-License-Identifier: BSD-2-Clause
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
SRC="$HERE/../gpu/src/grain.wgsl"
OUT="$HERE/web/grain-wgsl.mjs"
if grep -q -e '`' -e '\${' "$SRC"; then
    echo "grain.wgsl must not contain a backtick or \${" >&2
    exit 1
fi
{
    echo "// Generated by browser/sync-wgsl.sh from gpu/src/grain.wgsl: edit that file, then run the script."
    echo "// Copyright © 2026, divergentnn (av1-fullgrain). SPDX-License-Identifier: BSD-2-Clause"
    printf 'export const WGSL = `'
    cat "$SRC"
    echo '`;'
} > "$OUT"
echo "wrote $OUT"
